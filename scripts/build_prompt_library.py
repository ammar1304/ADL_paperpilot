#!/usr/bin/env python3
"""Build PROMPT_LIBRARY.md, the prompt library as one file (a graded deliverable), from prompts/.

The prompts themselves stay one file per version in prompts/<name>/v<n>.md, because that is
what pp-tools renders and what every run records; this script only gathers them, so the
single file can never disagree with what runs. Run it after changing a prompt:

    python scripts/build_prompt_library.py            # writes PROMPT_LIBRARY.md
    python scripts/build_prompt_library.py --check    # exit 1 if PROMPT_LIBRARY.md is out of date
"""

import argparse
import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
PROMPTS = REPO / "prompts"
OUT = REPO / "PROMPT_LIBRARY.md"


def parse(path: Path) -> dict:
    text = path.read_text(encoding="utf-8")
    m = re.match(r"^---\n(.*?)\n---\n(.*)$", text, re.S)
    meta = {}
    for line in m.group(1).splitlines():
        if ":" in line:
            k, v = line.split(":", 1)
            meta[k.strip()] = v.strip()
    body = m.group(2)
    notes = body.split("\n## System", 1)[0]
    system = body.split("## System", 1)[1].split("## User", 1)[0].strip() if "## System" in body else ""
    user = body.split("## User", 1)[1].strip() if "## User" in body else ""
    notes = re.sub(r"^# .*\n", "", notes.strip()).strip()
    return {"meta": meta, "notes": notes, "system": system, "user": user, "file": path.relative_to(REPO).as_posix()}


def fence(text: str) -> str:
    ticks = "````" if "```" in text else "```"
    return f"{ticks}text\n{text}\n{ticks}"


def build() -> str:
    active = json.loads((PROMPTS / "active.json").read_text(encoding="utf-8"))
    names = sorted(p.name for p in PROMPTS.iterdir() if p.is_dir())
    versions = {n: sorted((parse(f) for f in (PROMPTS / n).glob("v*.md")), key=lambda d: int(d["meta"]["version"][1:])) for n in names}
    out = [
        "# PaperPilot prompt library",
        "",
        "Every prompt PaperPilot sends to an LLM, with every version, why it changed, and the failure or measurement "
        "behind each change. Generated by `scripts/build_prompt_library.py` from `prompts/`, the files pp-tools renders "
        "at run time, so this document is exactly what runs. Failures cited as F-0NN are in `prompts/failure_log.md`; "
        "decisions cited as D-NN in `docs/DECISIONS.md`.",
        "",
        "## How prompts are used",
        "",
        "- **Prompts are files, not workflow text (D22).** n8n asks pp-tools to render the active version; each run step records the version used.",
        "- **The LLM gets a narrow task; code does the rest.** Code selects what the model sees (candidate sentences, retrieved passages, a figure) "
        "and validates what it answers (strict JSON schema, numbers that must appear in the source, evidence ids that must have been shown, "
        "a verifier that rejects papers retrieval never returned).",
        "- **A prompt changes only after a failure is observed or a comparison is measured,** and the old version is kept, so it can be compared and rolled back (`prompts/active.json`).",
        "",
        "## Summary",
        "",
        "| Prompt | Active | Versions | Role | Model | Techniques |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for n in names:
        a = next((v for v in versions[n] if v["meta"]["version"] == active.get(n)), versions[n][-1])
        m = a["meta"]
        out.append(f"| [{n}](#{n.lower()}) | {active.get(n, '-')} | {', '.join(v['meta']['version'] for v in versions[n])} | "
                   f"{m.get('role', '')} | {m.get('model', '')} | {m.get('technique', '')} |")
    for n in names:
        out += ["", f"## {n}", ""]
        a = active.get(n)
        for v in reversed(versions[n]):
            m = v["meta"]
            status = "active" if m["version"] == a else ("not active yet" if int(m["version"][1:]) > int((a or "v0")[1:]) else "kept for comparison")
            out += [f"### {n} {m['version']} ({status})", "",
                    f"- **File:** `{v['file']}`",
                    f"- **Role:** {m.get('role', '')}",
                    f"- **Model:** {m.get('model', '')}, temperature {m.get('temperature', '-')}",
                    f"- **Techniques:** {m.get('technique', '')}",
                    f"- **Variables:** {m.get('variables', '')}",
                    f"- **Called by:** {m.get('called_by', '')}", "",
                    v["notes"], "",
                    "**System prompt**", "", fence(v["system"]), "",
                    "**User prompt**", "", fence(v["user"]), ""]
    return "\n".join(out).rstrip() + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = build()
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print("PROMPT_LIBRARY.md is out of date: run python scripts/build_prompt_library.py")
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"Wrote {OUT.relative_to(REPO)} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
